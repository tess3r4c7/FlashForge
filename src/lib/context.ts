import { randomUUID } from "node:crypto";
import { AsyncLocalStorage } from "node:async_hooks";

// ─── Correlation IDs ────────────────────────────────────────────────────────
//
// In a distributed system, one user action flows through several processes:
//
//   POST /orders  →  outbox relay  →  RabbitMQ  →  payment worker  →  DB
//       (API)         (worker)                       (worker)
//
// Each process writes its own log lines. Without a shared "thread", grepping
// for "what happened to order 42" means eyeballing timestamps and hoping
// events appear in the right order.
//
// Two IDs solve this:
//
//   requestId     Unique per HTTP request. Already generated by Fastify
//                 (it calls it `req.id`). Ties together every log line
//                 produced while handling that one HTTP call.
//
//   correlationId Unique per BUSINESS ACTION, spanning processes. The API
//                 generates one when it creates a request. It's written
//                 into the outbox event, carried as a RabbitMQ header,
//                 and picked up by every consumer that handles the event.
//
//                 With this, you can grep the combined API + worker logs
//                 for a single correlation ID and see the ENTIRE journey:
//                 HTTP request → outbox → publish → consume → payment
//                 → confirm/cancel → notify.
//
// Implementation: Node's AsyncLocalStorage stores the current IDs in a
// "context" that flows automatically through async/await, callbacks, and
// promises — without passing parameters through every function signature.
// Fastify's onRequest hook sets it for HTTP requests; the consumer sets it
// when processing a message.

export interface RequestContext {
  /** Unique per HTTP request or message processing. */
  requestId: string;
  /** Spans across processes for a single business action. */
  correlationId: string;
}

const storage = new AsyncLocalStorage<RequestContext>();

/** Returns the current context, or undefined outside a request/consumer. */
export function getRequestContext(): RequestContext | undefined {
  return storage.getStore();
}

/** Runs `fn` with the given context active. */
export function runWithContext<T>(ctx: RequestContext, fn: () => T): T {
  return storage.run(ctx, fn);
}

/** Creates a fresh context (new requestId, optionally inheriting a correlationId). */
export function createContext(correlationId?: string): RequestContext {
  const id = randomUUID();
  return {
    requestId: id,
    correlationId: correlationId ?? id,
  };
}

